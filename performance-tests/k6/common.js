import http from 'k6/http';
import { check, sleep } from 'k6';
import { Trend, Rate } from 'k6/metrics';

export const BASE_URL = __ENV.BASE_URL || 'http://localhost:8080';
export const AUTH_ENABLED = (__ENV.AUTH_ENABLED || 'true') === 'true';
export const REGISTER_TEST_USER = (__ENV.REGISTER_TEST_USER || 'true') === 'true';
export const TEST_USER_PASSWORD = __ENV.TEST_USER_PASSWORD || 'Password123!';
export const TEST_USER_EMAIL = __ENV.TEST_USER_EMAIL || `perf-${Date.now()}@deliverxy.test`;
export const TEST_USER_IDENTIFIER = __ENV.TEST_USER_IDENTIFIER || TEST_USER_EMAIL;

export const apiLatency = new Trend('deliverxy_api_latency_ms');
export const apiErrors = new Rate('deliverxy_api_errors');

export function defaultHeaders(token = null) {
  const headers = {
    'Content-Type': 'application/json',
    Accept: 'application/json',
  };

  if (token) {
    headers.Authorization = `Bearer ${token}`;
  }

  return { headers };
}

