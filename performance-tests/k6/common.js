export function recordResponse(res, label) {
  apiLatency.add(res.timings.duration, { endpoint: label });
  apiErrors.add(res.status >= 400, { endpoint: label });
}

export function checkedRequest(method, path, body = null, token = null, expectedStatuses = [200]) {
  const url = `${BASE_URL}${path}`;
  const params = defaultHeaders(token);
  const payload = body === null ? null : JSON.stringify(body);

  let res;
  if (method === 'GET') {
    res = http.get(url, params);
  } else if (method === 'POST') {
    res = http.post(url, payload, params);
  } else if (method === 'PUT') {
    res = http.put(url, payload, params);
  } else if (method === 'PATCH') {
    res = http.patch(url, payload, params);
  } else if (method === 'DELETE') {
    res = http.del(url, payload, params);
  } else {
    throw new Error(`Unsupported method: ${method}`);
  }

  recordResponse(res, `${method} ${path}`);

  check(res, {
    [`${method} ${path} status is expected`]: (r) => expectedStatuses.includes(r.status),
    [`${method} ${path} response under 1500ms`]: (r) => r.timings.duration < 1500,
  });

  return res;
}

export function tryParseJson(res) {
  try {
    return res.json();
  } catch (_) {
    return null;
  }
}

export function extractAccessToken(authResponse) {
  const json = tryParseJson(authResponse);
  return json?.data?.accessToken || json?.accessToken || null;
}

export function registerUserIfNeeded(role = 'CLIENT') {
  if (!REGISTER_TEST_USER || !AUTH_ENABLED) {
    return;
  }

  const res = checkedRequest('POST', '/api/auth/register', buildRegisterPayload(role), null, [200, 201, 400, 409]);

  // 400/409 is acceptable when a stable TEST_USER_EMAIL already exists.
  check(res, {
    'register succeeded or user already exists': (r) => [200, 201, 400, 409].includes(r.status),
  });
}

export function login() {
  if (!AUTH_ENABLED) {
    return null;
  }

  const res = checkedRequest('POST', '/api/auth/login', buildLoginPayload(), null, [200]);
  const token = extractAccessToken(res);

  check(token, {
    'access token exists': (t) => !!t,
  });

  return token;
}

export function setupAuth(role = 'CLIENT') {
  registerUserIfNeeded(role);
  return login();
}

export function basicUserJourney(token) {
  checkedRequest('GET', '/actuator/health', null, null, [200]);
  checkedRequest('GET', '/api/auth/me', null, token, [200]);
  checkedRequest('GET', '/api/deliveries/mine', null, token, [200]);
  checkedRequest('POST', '/api/deliveries', buildDeliveryPayload(), token, [200, 201]);
  sleep(1);
}
